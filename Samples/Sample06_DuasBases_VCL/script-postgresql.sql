-- FluentORM Sample06 - PostgreSQL (o botao "Criar banco/tabela" faz o mesmo)
-- 1) Conectado no banco "postgres":
CREATE DATABASE fluentorm_sample06;

-- 2) Conectado no banco "fluentorm_sample06":
CREATE TABLE IF NOT EXISTS cliente (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome            VARCHAR(100)  NOT NULL,
  email           VARCHAR(120)  NULL,
  cpf             VARCHAR(14)   NULL,
  data_nascimento DATE          NULL,
  limite_credito  NUMERIC(12,2) NOT NULL DEFAULT 0,
  ativo           BOOLEAN       NOT NULL DEFAULT TRUE,
  origem          VARCHAR(40)   NULL,
  criado_em       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_cliente_nome ON cliente (nome);
